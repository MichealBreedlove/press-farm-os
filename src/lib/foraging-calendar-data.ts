/**
 * Item count per category — used by the filter chips.
 */
export function countByCategory(): Record<ForageCategory, number> {
  return FORAGE_ITEMS.reduce(
    (acc, item) => {
      acc[item.category]++;
      return acc;
    },
    { mushrooms: 0, greens: 0, berries: 0, fruits: 0 } as Record<ForageCategory, number>,
  );
}

export function countInvasive(): number {
  return FORAGE_ITEMS.filter((i) => i.isInvasive).length;
}

/**
 * Items in peak in a given month — used by the spotlight and "X species can be
 * found in {month}" stat.
 */
export function itemsInPeak(month: number): ForageItem[] {
  return FORAGE_ITEMS.filter((i) => i.peak.includes(month));
}

/**
 * Items where the given month is either peak or shoulder — used for the
 * Month View species count (matches Bay Forager's tally).
 */
export function itemsAvailable(month: number): ForageItem[] {
  return FORAGE_ITEMS.filter(
    (i) => i.peak.includes(month) || i.shoulder?.includes(month),
  );
}
