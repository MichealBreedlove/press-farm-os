/**
 * Press Farm OS — Foraging Calendar Data
 *
 * Bay Area seasonal foraging reference, mirroring thebayforager.com's
 * 85-species catalog. Categories, regions, and species names are matched
 * to their site. Months are 1–12 (Jan = 1). `peak` is the strongest
 * window; `shoulder` extends either side where the item is still findable.
 *
 * Microclimates of The Bay routinely shift these windows by 2–6 weeks —
 * treat peak and shoulder ratings as rough guidance, not a schedule.
 *
 * Sources: thebayforager.com, ForageSF, Mycological Society of San
 * Francisco, Bay Nature, Yerba Buena Chapter CNPS, and "The Bay Area
 * Forager" (Andler & Feinstein, Heyday Books). Always positively identify
 * before consuming, and respect protected areas — foraging is prohibited
 * in most CA state parks and all national parks except for limited
 * personal mushroom quotas in a few.
 */

export type ForageCategory = "mushrooms" | "greens" | "berries" | "fruits";

export type ForageRegion = "marin" | "east-bay" | "peninsula" | "santa-cruz";

export interface ForageItem {
  slug: string;
  name: string;
  scientificName?: string;
  category: ForageCategory;
  /** Bay Area regions where the species is reliably found. */
  regions: ForageRegion[];
  /** Cross-cutting tag — shows up in the Invasives filter regardless of category. */
  isInvasive?: boolean;
  /** Months (1–12) when the item is at peak / ready to harvest. */
  peak: number[];
  /** Months (1–12) where the item is on the way in or fading out. */
  shoulder?: number[];
  habitat: string;
  notes: string;
  /** Optional caution — toxic lookalikes, allergen, or legal restriction. */
  caution?: string;
  /**
   * Override for the Wikipedia page used to source the identification photo.
   * Defaults to scientificName with underscores (with "spp." stripped). Only
   * set when the auto-derived title doesn't match a real WP page.
   */
  wikiTitle?: string;
}

/**
 * Derive the Wikipedia page title for a foraging item. Used by the
 * client-side image fetcher to pull a thumbnail from the Wikipedia REST
 * API for identification.
 */
export function wikiTitleFor(item: ForageItem): string {
  if (item.wikiTitle) return item.wikiTitle;
  if (item.scientificName) {
    return item.scientificName
      .replace(/\s+spp\.$/i, "")
      .trim()
      .replace(/\s+/g, "_");
  }
  return item.name.replace(/\s+/g, "_");
}

