import { redirect, notFound } from "next/navigation";
import { createClient } from "@/lib/supabase/server";
import { createAdminClient } from "@/lib/supabase/admin";
import { EditorialHero } from "@/components/shared/EditorialHero";
import { listTaskPeople, ownerOf } from "@/lib/tasks/people";
import { isMicrogreenTask } from "@/lib/tasks/assign";
import { EditTaskForm } from "@/components/admin/tasks/EditTaskForm";
import type { FarmTask } from "@/types/database";

export const dynamic = "force-dynamic";

interface PageProps {
  params: Promise<{ id: string }>;
}

export default async function EditTaskPage({ params }: PageProps) {
  const { id } = await params;
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) redirect("/login");

  const admin = createAdminClient();

  const [{ data: taskRow }, { data: items }] = await Promise.all([
    admin.from("farm_tasks").select("*").eq("id", id).maybeSingle(),
    admin
      .from("items")
      .select("id, name")
      .eq("is_archived", false)
      .order("name", { ascending: true }),
  ]);

  if (!taskRow) notFound();
  const allPeople = await listTaskPeople(admin);
  const people = isMicrogreenTask(taskRow as FarmTask)
    ? allPeople.filter((p) => p.role === "admin")
    : allPeople;
  const task = taskRow as FarmTask;
  const { data: chainRows } = task.stage_group_id
    ? await (admin as any)
        .from("farm_tasks")
        .select("id, title, stage_index, status, due_date")
        .eq("stage_group_id", task.stage_group_id)
        .order("stage_index", { ascending: true })
    : { data: null };
  const chain = (chainRows ?? [
    { id: task.id, title: task.title, stage_index: 1, status: task.status, due_date: task.due_date },
  ]) as { id: string; title: string; stage_index: number | null; status: string; due_date: string }[];
  // Microgreen tasks stay with the farm owner — farm hands aren't offered.

  return (
    <div className="min-h-screen">
      <EditorialHero
        eyebrow="Operations"
        title="Edit task"
        subtitle={
          task.stage_group_id && chain.length > 1
            ? `Step ${task.stage_index} of ${chain.length}`
            : task.source === "manual"
            ? "One-off task"
            : `Generated · ${task.source}` // hint that auto tasks may be regenerated by cron
        }
        flower="borage-2"
        backHref="/admin/tasks"
      />
      <div className="max-w-md mx-auto px-4 py-6">
        {task.source !== "manual" && (
          <div className="mb-4 rounded-md border border-amber-200 bg-amber-50 px-3 py-2 text-xs text-amber-800">
            This task was generated automatically. Your edits stick, but the
            nightly cron may supersede them if the underlying schedule
            changes.
          </div>
        )}
        <EditTaskForm task={task} items={items ?? []} people={people} ownerName={ownerOf(people)?.name ?? null} chain={chain} />
      </div>
    </div>
  );
}
